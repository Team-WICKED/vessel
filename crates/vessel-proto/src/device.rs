//! Paired devices: scopes, credentials, the in-channel preamble, and
//! pairing links (ADR 0010, protocol 4).
//!
//! A device is one client machine with its own credential for a node. It is
//! created by an expiring, single-use invitation and can be revoked on its
//! own, unlike the node token, which is shared by everything local.

use std::fmt;
use std::str::FromStr;

use chrono::{DateTime, Utc};
use serde::{Deserialize, Serialize};

use crate::id::{DeviceId, NodeId};
use crate::key::{KeyTextError, NodePublicKey, base64url, base64url_array, serde_via_text};
use crate::node::NodeInfo;

/// What a caller may do. Every RPC method declares the one it needs
/// (`Method::scope`); the node checks it for calls from a paired device.
/// The node token and the local socket hold every scope.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Scope {
    /// Look: node info, harnesses, sessions, logs, subscriptions.
    Read,
    /// Act on sessions: create, send input, kill.
    Operate,
    /// Change the node: stop it, manage devices.
    Admin,
}

impl Scope {
    /// Every scope, lowest first.
    pub const ALL: [Self; 3] = [Self::Read, Self::Operate, Self::Admin];
}

/// Declares a fixed-size secret: base64url on the wire, never printed.
macro_rules! secret {
    ($(#[$meta:meta])* $name:ident, $len:literal) => {
        $(#[$meta])*
        #[derive(Clone, PartialEq, Eq)]
        pub struct $name([u8; $len]);

        impl $name {
            /// Wrap secret bytes (generated by the node from the OS RNG).
            #[must_use]
            pub const fn from_bytes(bytes: [u8; $len]) -> Self {
                Self(bytes)
            }

            /// The secret bytes. Callers compare them in constant time or
            /// hash them; they never log them.
            #[must_use]
            pub const fn expose(&self) -> &[u8; $len] {
                &self.0
            }
        }

        impl fmt::Debug for $name {
            fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
                f.write_str(concat!(stringify!($name), "(<redacted>)"))
            }
        }

        impl fmt::Display for $name {
            /// The wire text. Only for writing credential files and links;
            /// `Debug` is what logs see.
            fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
                f.write_str(&base64url(&self.0))
            }
        }

        impl FromStr for $name {
            type Err = KeyTextError;

            fn from_str(s: &str) -> Result<Self, Self::Err> {
                base64url_array(s.trim()).map(Self)
            }
        }

        serde_via_text!($name);
    };
}

secret! {
    /// A device's credential: 256 random bits, sent only inside a secure
    /// channel, stored on the node as a hash only.
    DeviceSecret, 32
}

secret! {
    /// The single-use secret of a pairing invitation: 128 random bits.
    InvitationSecret, 16
}

/// A paired device as the node reports it.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct DeviceInfo {
    /// Its id.
    pub id: DeviceId,
    /// The name given at pairing (the client machine's name by default).
    pub label: String,
    /// When it was paired.
    pub created_at: DateTime<Utc>,
    /// When it last authenticated.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub last_seen: Option<DateTime<Utc>>,
    /// What it may do.
    pub scopes: Vec<Scope>,
    /// When it was revoked, if it was.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub revoked_at: Option<DateTime<Utc>>,
}

/// The first frame a client sends inside a secure channel, before `hello`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum Preamble {
    /// A paired device presents its credential.
    DeviceAuth {
        /// The device.
        device: DeviceId,
        /// Its credential.
        secret: DeviceSecret,
    },
    /// A new device redeems a pairing invitation.
    PairRequest {
        /// The invitation from the pairing link.
        invite: InvitationSecret,
        /// What to call this device on the node.
        device_name: String,
    },
}

/// Why a node refused a preamble. Deliberately coarse: a refusal must not
/// tell an attacker which part was wrong beyond what a legitimate user needs.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum RefusalReason {
    /// No such device, or the credential does not match.
    UnknownDevice,
    /// The device was revoked.
    Revoked,
    /// The invitation is unknown, used, or expired.
    InvalidInvitation,
    /// The node cannot authenticate right now (for example it is stopping).
    Unavailable,
}

/// The node's answer to a [`Preamble`].
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum PreambleReply {
    /// The device is authenticated; `hello` follows.
    Authenticated {
        /// The device.
        device: DeviceId,
    },
    /// The invitation was redeemed; the client stores the credential, and
    /// `hello` follows on the same channel.
    Paired {
        /// The new device's id.
        device: DeviceId,
        /// Its credential.
        secret: DeviceSecret,
        /// The node, so the client can pin its id. Boxed: the other replies
        /// are a few bytes, and this one is sent once per pairing.
        node: Box<NodeInfo>,
    },
    /// Refused; the node closes the channel after sending this.
    Refused {
        /// Why.
        reason: RefusalReason,
    },
}

/// A route to a node: a `ws://` or `wss://` URL, for a relay or a direct
/// address. Only the scheme is checked here; reachability is the client's.
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct RouteUrl(String);

/// A route URL with a scheme other than `ws://` or `wss://`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct InvalidRoute(pub String);

impl fmt::Display for InvalidRoute {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "`{}` is not a ws:// or wss:// URL", self.0)
    }
}

impl std::error::Error for InvalidRoute {}

impl RouteUrl {
    /// The URL text.
    #[must_use]
    pub fn as_str(&self) -> &str {
        &self.0
    }

    /// Whether it needs TLS.
    #[must_use]
    pub fn is_tls(&self) -> bool {
        self.0.starts_with("wss://")
    }
}

impl fmt::Display for RouteUrl {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.0)
    }
}

impl FromStr for RouteUrl {
    type Err = InvalidRoute;

    fn from_str(s: &str) -> Result<Self, Self::Err> {
        let text = s.trim();
        let rest = text
            .strip_prefix("wss://")
            .or_else(|| text.strip_prefix("ws://"));
        match rest {
            Some(host) if !host.is_empty() => Ok(Self(text.to_owned())),
            Some(_) | None => Err(InvalidRoute(text.to_owned())),
        }
    }
}

serde_via_text!(RouteUrl);

/// Everything a client needs to pair with a node, carried by a pairing link.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct PairingOffer {
    /// The node's id (pinned like an SSH node's).
    pub node: NodeId,
    /// The node's static key (pinned; the handshake checks it).
    pub key: NodePublicKey,
    /// Relays the node is registered with, in preference order.
    #[serde(default)]
    pub relays: Vec<RouteUrl>,
    /// Direct addresses the node was told to advertise (`--public`).
    #[serde(default)]
    pub direct: Vec<RouteUrl>,
    /// The single-use invitation.
    pub invite: InvitationSecret,
    /// When the invitation expires.
    pub expires: DateTime<Utc>,
}

const LINK_PREFIX: &str = "vessel://pair#";

/// A pairing link: `vessel://pair#` followed by the base64url JSON of a
/// [`PairingOffer`]. The offer sits after `#` so that, if a link is ever
/// opened through a web page, the fragment never reaches a server.
#[derive(Clone, PartialEq, Eq)]
pub struct PairingLink(String);

/// Why a pairing link did not parse.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum LinkError {
    /// It does not start with `vessel://pair#`.
    Prefix,
    /// The fragment is not base64url.
    Encoding,
    /// The decoded offer is not valid.
    Offer(String),
}

impl fmt::Display for LinkError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Prefix => f.write_str("a pairing link starts with `vessel://pair#`"),
            Self::Encoding => f.write_str("the pairing link is damaged (not base64url)"),
            Self::Offer(reason) => write!(f, "the pairing link is damaged: {reason}"),
        }
    }
}

impl std::error::Error for LinkError {}

impl PairingLink {
    /// Encode an offer.
    ///
    /// # Errors
    /// Fails only if the offer cannot be serialised, which its types rule out
    /// in practice.
    pub fn encode(offer: &PairingOffer) -> Result<Self, serde_json::Error> {
        let json = serde_json::to_vec(offer)?;
        Ok(Self(format!("{LINK_PREFIX}{}", base64url(&json))))
    }

    /// Decode the offer.
    ///
    /// # Errors
    /// Fails if the text is not a pairing link or its offer is damaged.
    pub fn decode(&self) -> Result<PairingOffer, LinkError> {
        use base64::Engine as _;
        let encoded = self.0.strip_prefix(LINK_PREFIX).ok_or(LinkError::Prefix)?;
        let json = base64::engine::general_purpose::URL_SAFE_NO_PAD
            .decode(encoded)
            .map_err(|_decode| LinkError::Encoding)?;
        serde_json::from_slice(&json).map_err(|error| LinkError::Offer(error.to_string()))
    }

    /// The link text, for printing (it contains a secret: print it only to
    /// the person pairing, never to logs).
    #[must_use]
    pub fn expose(&self) -> &str {
        &self.0
    }
}

impl fmt::Debug for PairingLink {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str("PairingLink(<redacted>)")
    }
}

impl FromStr for PairingLink {
    type Err = LinkError;

    fn from_str(s: &str) -> Result<Self, Self::Err> {
        let link = Self(s.trim().to_owned());
        link.decode().map(|_offer| link)
    }
}

impl Serialize for PairingLink {
    fn serialize<S: serde::Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
        serializer.serialize_str(&self.0)
    }
}

impl<'de> Deserialize<'de> for PairingLink {
    fn deserialize<D: serde::Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        let text = std::borrow::Cow::<'de, str>::deserialize(deserializer)?;
        text.parse().map_err(serde::de::Error::custom)
    }
}

/// `device.invite` (protocol 4): make a pairing link. Needs `Admin`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct InviteDevice {
    /// Label for the device that redeems it (it may name itself instead).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub label: Option<String>,
    /// How long the invitation is valid, in seconds (the node caps it).
    pub ttl_secs: u32,
}

/// Reply to `device.invite`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Invitation {
    /// The link to hand to the new device.
    pub link: PairingLink,
    /// When it expires.
    pub expires: DateTime<Utc>,
}

/// `device.list` (protocol 4): every device, revoked ones included.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub struct ListDevices;

/// `device.revoke` (protocol 4): revoke a device and close its connections.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub struct RevokeDevice {
    /// Which device.
    pub device: DeviceId,
}

#[cfg(test)]
mod tests {
    use super::*;

    fn offer() -> PairingOffer {
        PairingOffer {
            node: NodeId::random(),
            key: NodePublicKey::from_bytes([9; 32]),
            relays: vec!["wss://relay.example/vessel".parse().unwrap()],
            direct: vec!["ws://203.0.113.5:7077".parse().unwrap()],
            invite: InvitationSecret::from_bytes([3; 16]),
            expires: DateTime::UNIX_EPOCH,
        }
    }

    #[test]
    fn pairing_links_round_trip_and_reject_damage() {
        let offer = offer();
        let link = PairingLink::encode(&offer).unwrap();
        assert!(link.expose().starts_with("vessel://pair#"));
        assert_eq!(link.decode().unwrap(), offer);
        assert_eq!(link.expose().parse::<PairingLink>().unwrap(), link);
        assert!(matches!(
            "https://x#abc".parse::<PairingLink>(),
            Err(LinkError::Prefix)
        ));
        assert!(matches!(
            "vessel://pair#!!".parse::<PairingLink>(),
            Err(LinkError::Encoding)
        ));
    }

    #[test]
    fn secrets_never_print_through_debug() {
        let secret = DeviceSecret::from_bytes([1; 32]);
        assert_eq!(format!("{secret:?}"), "DeviceSecret(<redacted>)");
        let link = PairingLink::encode(&offer()).unwrap();
        assert_eq!(format!("{link:?}"), "PairingLink(<redacted>)");
        assert_eq!(secret.to_string().parse::<DeviceSecret>().unwrap(), secret);
    }

    #[test]
    fn routes_must_be_websocket_urls() {
        assert!("wss://relay.example".parse::<RouteUrl>().unwrap().is_tls());
        assert!(!"ws://10.0.0.1:7077".parse::<RouteUrl>().unwrap().is_tls());
        assert!("https://relay.example".parse::<RouteUrl>().is_err());
        assert!("ws://".parse::<RouteUrl>().is_err());
    }

    #[test]
    fn preamble_frames_are_tagged() {
        let auth = Preamble::DeviceAuth {
            device: DeviceId::random(),
            secret: DeviceSecret::from_bytes([2; 32]),
        };
        let json = serde_json::to_string(&auth).unwrap();
        assert!(json.starts_with(r#"{"type":"device_auth""#));
        assert_eq!(serde_json::from_str::<Preamble>(&json).unwrap(), auth);
        let refused = PreambleReply::Refused {
            reason: RefusalReason::Revoked,
        };
        assert_eq!(
            serde_json::to_string(&refused).unwrap(),
            r#"{"type":"refused","reason":"revoked"}"#
        );
    }
}
